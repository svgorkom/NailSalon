const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const icons = join(root, 'node_modules', '@phosphor-icons', 'core', 'assets', 'fill');

const lines = Object.entries(STICKERS).map(([kind, icon]) => {
  const svg = readFileSync(join(icons, `${icon}-fill.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length !== 1 || /<(circle|rect|ellipse|polygon|line)\b/.test(svg)) throw new Error(`${icon}: expected exactly one path`);
  const [minX, minY, maxX, maxY] = svgPathBbox(paths[0]);
  const scale = 100 / Math.max(maxX - minX, maxY - minY);
  const d = svgpath(paths[0])
    .translate(-(minX + maxX) / 2, -(minY + maxY) / 2)
    .scale(scale)
    .abs()
    .round(1)
    .toString();
  return `  ${/^[a-z]+$/.test(kind) ? kind : `'${kind}'`}: '${d}',`;
});

const out = `// Generated by tools/stickers/generate.mjs from Phosphor Icons (fill), MIT licence. Do not edit by hand.

/** Library stickers as SVG path data, centred in a box from -50 to 50. */
export const LIBRARY_STICKER_PATHS = {
${lines.join('\n')}
} as const;
`;
writeFileSync(join(root, 'src', 'scene', 'stickerLibrary.ts'), out);
console.log(`Wrote ${lines.length} stickers.`);
